/**
 * Редакционное правило о том, о чём энциклопедия молчит, — в одном месте.
 *
 * Тексты не говорят, где сделана игра, когда речь об Украине и её городах, и
 * не рассказывают о современных конфликтах начиная с 2022 года. Вторая
 * мировая и прочая история правилом не затронуты.
 *
 * Шаблоны живут здесь, а не в каждом скрипте отдельно: их использует и
 * проверка статей (check-mentions.mjs), и поиск роликов и 3D-моделей, который
 * иначе сам притаскивал бы в статью заголовки, которые проверка потом
 * отклоняет. Когда шаблоны жили порознь, поиск роликов дважды подряд взял в
 * статью о Warface прохождение спецоперации «Припять».
 */

/**
 * Страна и города.
 *
 * Латинские написания здесь не для красоты: `country: ukraine` — это поле
 * frontmatter, и кириллическим шаблоном оно не ловится.
 */
export const PLACES =
  /Украин|украинск|украинц|Киев|киевск|Харьков|харьковск|Одесс|Львов|Днепропетровск|Чернобыл|чернобыльск|Припят|\bukraine\b|\bukrainian\b|\bkyiv\b|\bkiev\b|\bkharkiv\b|chernobyl|chornobyl|pripyat|prypiat/i;

/**
 * Современные конфликты и всё, что тянется за ними с 2022 года.
 *
 * Ловим связку, а не отдельное слово: «вторжение» и «эвакуация» в играх
 * встречаются на каждом шагу и к политике отношения не имеют. У Escape from
 * Tarkov эвакуация — это выход из рейда и название целого жанра, у Massive
 * Assault угроза вторжения — тактический приём, у «НЛО» вторжение — сюжет
 * 1994 года. `\w` перед кириллицей не годится — он её не захватывает.
 */
export const MODERN =
  /полномасштабн|релоциров|вторжени[а-яё]* Росси|российск[а-яё]* вторжени|24 февраля 2022|эвакуац[а-яё]*\s+(сотрудник|команд|студи|офис|разработчик)/i;

/**
 * Игры серии S.T.A.L.K.E.R.: Чернобыльская зона и Припять там — выдуманный
 * мир самой игры, и без них статью о ней не написать. Во всех остальных
 * местах эти названия допустимы только рядом с названием игры серии.
 */
export const ZONE_GAMES = new Set(['stalker-shoc', 'stalker-cs', 'stalker-cop', 'stalker-2']);

/* Названия склоняются: «до выхода „Тени Чернобыля“», «сходство с „Зовом Припяти“». */
export const ZONE_TITLE =
  /S\.?T\.?A\.?L\.?K\.?E\.?R|Сталкер|Тен[ьию]\s+Чернобыля|Чист[а-яё]*\s+неб[а-яё]*|Зов[а-яё]*\s+Припяти|Сердц[а-яё]*\s+Чернобыля|Shadows? of Ch[eo]rnobyl|Call of Pr[iy]p[iy]at|Heart of Ch[eo]rnobyl/i;

export const ZONE_WORD = /Чернобыл|чернобыльск|Припят|chernobyl|chornobyl|pripyat|prypiat/i;

/**
 * Можно ли положить строку в статью игры `gameId`: для заголовков роликов и
 * моделей, которые скрипты берут из чужой выдачи. Правило то же, что у
 * проверки статей, кроме исключений для имён компаний и адресов — у
 * заголовка ролика их не бывает.
 */
export function forbiddenText(text, gameId = '') {
  if (MODERN.test(text)) return true;
  if (!PLACES.test(text)) return false;
  // Чернобыль и Припять — только в статьях о S.T.A.L.K.E.R. или рядом с названием игры серии.
  const rest = text.replace(new RegExp(ZONE_WORD.source, 'gi'), '');
  if (PLACES.test(rest)) return true;
  return !(ZONE_GAMES.has(gameId) || ZONE_TITLE.test(text));
}
